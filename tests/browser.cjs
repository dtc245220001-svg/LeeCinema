const {chromium} = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.TEST_URL || 'http://localhost:3003';
(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors = [];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('400')&&!m.text().includes('404'))errors.push(m.text());});
    fs.mkdirSync('docs/evidence',{recursive:true});
    await page.goto(base);
    await page.locator('.movie').first().waitFor();
    assert.equal(await page.locator('.movie').count(),12);
    await page.waitForFunction(()=>[...document.querySelectorAll('.movie img')].every(i=>i.complete&&i.naturalWidth>0));
    assert(await page.locator('.hero').isVisible());
    assert.equal(await page.locator('.hero-art').evaluate(i=>i.complete&&i.naturalWidth>0),true);
    assert.equal(await page.locator('.movie img').evaluateAll(imgs=>imgs.every(i=>i.src.endsWith('.webp'))),true);
    await page.screenshot({path:'docs/evidence/01-home-desktop.png'});
    await page.screenshot({path:'docs/evidence/02-movies-desktop.png',fullPage:true});
    await page.getByRole('button',{name:'Hoạt hình',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.movie').length===1);
    assert.match(await page.locator('.movie h3').innerText(),/Vương quốc mây/);
    await page.getByRole('button',{name:'Tất cả',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.movie').length===12);
    await page.locator('#search').fill('zzzzzzzz');
    await page.waitForFunction(()=>document.querySelector('#movie-status').textContent==='Không có phim phù hợp.');
    assert.equal(await page.locator('.movie').count(),0);
    await page.locator('#search').fill('vũ trụ');
    await page.waitForFunction(()=>document.querySelectorAll('.movie').length===1);
    await page.locator('.movie button').click();
    await page.locator('.seat').first().waitFor();
    assert.equal(await page.locator('.seat').count(),40);
    await page.locator('.seat:not([disabled])').first().click();
    assert.equal(await page.locator('.seat.selected').count(),1);
    assert(!(await page.locator('#confirm').isDisabled()));
    await page.screenshot({path:'docs/evidence/04-seats.png',fullPage:true});
    await page.locator('[name=name]').fill('Khach Trinh Duyet');
    await page.locator('[name=email]').fill('browser@example.test');
    await page.locator('#confirm').click();
    await page.locator('#receipt:not([hidden])').waitFor();
    assert.match(await page.locator('#receipt-code').innerText(),/^VE-[A-F0-9]{16}$/);
    await page.screenshot({path:'docs/evidence/05-receipt.png',fullPage:true});
    await page.locator('#navigation a[href="#schedule"]').click();
    await page.locator('.schedule-card').first().waitFor();
    assert.equal(await page.locator('.date-tab').count(),7);
    assert.equal(await page.locator('.schedule-card').count(),12);
    await page.screenshot({path:'docs/evidence/06-schedule.png',fullPage:true});
    const sessions = await fetch(base+'/api/showtimes').then(r=>r.json());
    const activeDate = await page.locator('.date-tab.active').getAttribute('data-date');
    const preferred = sessions.find(s=>s.movie_id===4&&s.starts_at.startsWith(activeDate));
    const card = page.locator('.schedule-card').filter({has:page.locator('h3',{hasText:'Vương quốc mây'})});
    await card.locator('.showtime-button').first().click();
    await page.locator('.seat').first().waitFor();
    assert.equal(await page.locator('#showtime').inputValue(),String(preferred.id));
    await page.locator('#navigation a[href="#about"]').click();
    await page.locator('#about').waitFor({state:'visible'});
    assert(await page.locator('#about').isVisible());
    assert(!(await page.locator('#booking').isVisible()));
    await page.locator('#navigation a[href="#guide"]').click();
    await page.locator('#guide').waitFor({state:'visible'});
    assert(await page.locator('#guide').isVisible());
    assert.equal(await page.locator('.faq details').count(),5);
    await page.setViewportSize({width:390,height:844});
    await page.goto(base);
    await page.locator('.movie').first().waitFor();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.screenshot({path:'docs/evidence/03-mobile.png',fullPage:true});
    await page.locator('#menu-toggle').click();
    assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'true');
    await page.locator('#navigation a[href="#schedule"]').click();
    await page.locator('.schedule-card').first().waitFor();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.deepEqual(errors,[]);
    console.log('PASS: 12 WebP posters, home, genres/search, booking receipt, live schedule/preselected session, about/guide, mobile menu and no JS/CSP errors or overflow.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
